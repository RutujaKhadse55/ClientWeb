export function getArticleById(id) {
  return newsArticles.find(a => a.id === id || a.slug === id) || newsArticles[0];
}

export function getArticlesByCategory(category) {
  if (!category || category.toLowerCase() === 'all') return newsArticles;
  return newsArticles.filter(a => 
    a.category.toLowerCase() === category.toLowerCase() || 
    a.subcategory.toLowerCase().includes(category.toLowerCase())
  );
}

export function getTrendingArticles() {
  return newsArticles
    .filter(a => a.isTrending)
    .sort((a, b) => (a.trendingRank || 99) - (b.trendingRank || 99))
    .slice(0, 5);
}

export function getExplainedArticles() {
  return newsArticles.filter(a => a.isExplained || a.category === 'Explained');
}

export function getOpinionArticles() {
  return newsArticles.filter(a => a.isOpinion || a.category === 'Opinion');
}

export function getRelatedArticles(articleId) {
  const current = getArticleById(articleId);
  if (!current) return newsArticles.slice(0, 3);
  
  if (current.relatedArticleIds && current.relatedArticleIds.length > 0) {
    const related = current.relatedArticleIds
      .map(id => newsArticles.find(a => a.id === id))
      .filter(Boolean);
    if (related.length > 0) return related;
  }

  return newsArticles
    .filter(a => a.id !== current.id && (a.category === current.category || a.subcategory === current.subcategory))
    .slice(0, 3);
}

export function searchArticles(query, category = 'all') {
  const q = (query || '').toLowerCase().trim();
  let results = newsArticles;

  if (category && category.toLowerCase() !== 'all') {
    results = results.filter(a => a.category.toLowerCase() === category.toLowerCase());
  }

  if (!q) return results;

  return results.filter(a => 
    a.title.toLowerCase().includes(q) ||
    a.subtitle.toLowerCase().includes(q) ||
    a.intro.toLowerCase().includes(q) ||
    a.tags.some(t => t.toLowerCase().includes(q))
  );
}
